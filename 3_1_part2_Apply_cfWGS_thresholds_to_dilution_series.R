# Generic patient-line renderer shared by cfDNA, BM-informed, and
# fragmentomics panels. Feature labels, probability thresholds, and the
# optional confirmatory boundary are parameters so all assay views use the
# same axis transformation, replicate grouping, and visual grammar.
make_blood_patient_line_plot <- function(plot_dat,
                                         plot_title,
                                         patient_specific = FALSE,
                                         show_legend = TRUE,
                                         x_col = "LOD",
                                         x_breaks = major_breaks,
                                         x_minor_breaks = minor_breaks,
                                         x_labels = format_lod_percent,
                                         facet_label_map = facet_labels_blood_hc,
                                         probability_thresholds = blood_thresholds,
                                         confirmatory_feature = "Blood_zscore_only_sites_prob",
                                         confirmatory_threshold = 0.380,
                                         healthy_control_dat = NULL,
                                         feature_y_transform = c("identity", "pseudo_log"),
                                         feature_pseudo_log_sigma = 0.00001) {
  feature_y_transform <- match.arg(feature_y_transform)
  if (!is.numeric(feature_pseudo_log_sigma) ||
      length(feature_pseudo_log_sigma) != 1L ||
      !is.finite(feature_pseudo_log_sigma) ||
      feature_pseudo_log_sigma <= 0) {
    stop("feature_pseudo_log_sigma must be one finite positive number.")
  }
  if (nrow(plot_dat) == 0) {
    stop("No rows available for patient-line dilution plot.")
  }
  annotation_df <- summarise_spearman_for_panels(plot_dat, x_col = x_col)
  color_var <- if ("patient_legend_label" %in% names(plot_dat)) {
    "patient_legend_label"
  } else {
    "Patient"
  }
  color_label <- "Patient (mutations tracked)"

  feature_df <- plot_dat %>% filter(.data$panel_type == "Feature")
  probability_df <- plot_dat %>% filter(.data$panel_type == "Probability")
  if (is.null(healthy_control_dat)) {
    healthy_control_dat <- tibble(
      feature = character(),
      value = numeric(),
      healthy_control_plot_x = numeric()
    )
  }
  required_hc_columns <- c("feature", "value", "healthy_control_plot_x")
  missing_hc_columns <- setdiff(required_hc_columns, names(healthy_control_dat))
  if (length(missing_hc_columns)) {
    stop(
      "Healthy-control overlay is missing column(s): ",
      paste(missing_hc_columns, collapse = ", "),
      call. = FALSE
    )
  }
  healthy_control_medians <- healthy_control_dat %>%
    filter(!is.na(.data$value)) %>%
    group_by(.data$feature) %>%
    summarise(median_value = median(.data$value), .groups = "drop")

  p_feature_lines <- ggplot(
    feature_df,
    aes(x = .data[[x_col]], y = .data$value, group = .data$line_group)
    ) +
    geom_line(aes(color = .data[[color_var]], linetype = .data$replicate_id),
              linewidth = 0.45, alpha = 0.75) +
    geom_point(aes(color = .data[[color_var]]),
               shape = 16, size = 1.8, alpha = 0.9) +
    {
      if (nrow(healthy_control_medians)) {
        geom_hline(
          data = healthy_control_medians,
          aes(yintercept = .data$median_value),
          inherit.aes = FALSE,
          linetype = "dotted",
          color = "gray50",
          linewidth = 0.5
        )
      }
    } +
    {
      if (nrow(healthy_control_dat)) {
        geom_point(
          data = healthy_control_dat,
          aes(
            x = .data$healthy_control_plot_x,
            y = .data$value
          ),
          inherit.aes = FALSE,
          color = "gray60",
          shape = 16,
          size = 1.5,
          alpha = 0.6
        )
      }
    } +
    facet_wrap(
      ~ feature,
      scales = "free_y",
      labeller = as_labeller(facet_label_map)
    ) +
    geom_text(
      data = annotation_df,
      aes(x = 0.025, y = Inf, label = .data$label),
      hjust = 0, vjust = 1.2, size = 3, inherit.aes = FALSE
    ) +
    {
      if (feature_y_transform == "pseudo_log") {
        scale_y_continuous(
          trans = scales::pseudo_log_trans(
            sigma = feature_pseudo_log_sigma,
            base = 10
          ),
          breaks = function(limits) {
            max_abs <- max(abs(limits), na.rm = TRUE)
            if (!is.finite(max_abs) || max_abs == 0) return(0)
            max_exponent <- floor(log10(max_abs))
            magnitudes <- 10 ^ seq(max_exponent - 3, max_exponent)
            candidates <- c(-rev(magnitudes), 0, magnitudes)
            candidates[candidates >= limits[[1]] & candidates <= limits[[2]]]
          }
        )
      }
    } +
    scale_x_continuous(
      trans = compose_trans("log10", "reverse"),
      breaks = x_breaks,
      minor_breaks = x_minor_breaks,
      labels = x_labels
    ) +
    annotation_logticks(sides = "b", base = 10) +
    scale_linetype_manual(
      name = "Replicate",
      values = c(rep01 = "solid", rep02 = "dashed", single = "dotdash")
    ) +
    labs(
      x = "Log tumour fraction (%)",
      y = if (feature_y_transform == "pseudo_log") {
        "Feature value (signed pseudo-log scale)"
      } else {
        "Feature value"
      },
      color = color_label
    ) +
    guides(
      color = guide_legend(order = 1),
      linetype = "none"
    ) +
    theme_classic(base_size = 10) +
    theme(
      strip.text = element_text(face = "bold"),
      panel.border = element_rect(color = "black", fill = NA),
      axis.ticks = element_line(color = "black"),
      axis.text.x = element_text(angle = 45, hjust = 1, vjust = 1, size = 6),
      axis.title.x = element_text(margin = margin(t = 8)),
      plot.margin = margin(5.5, 5.5, 18, 5.5),
      legend.position = if (show_legend) "right" else "none"
    )

  p_probability_lines <- ggplot(
    probability_df,
    aes(x = .data[[x_col]], y = .data$value, group = .data$line_group)
  ) +
    geom_hline(
      data = probability_thresholds,
      aes(yintercept = .data$thr),
      linetype = "dashed",
      color = "gray40"
    ) +
    {
      if (!is.null(confirmatory_feature) && !is.null(confirmatory_threshold)) {
        geom_hline(
          data = data.frame(feature = confirmatory_feature, thr = confirmatory_threshold),
          aes(yintercept = .data$thr),
          linetype = "dashed",
          color = "steelblue"
        )
      }
    } +
    geom_line(aes(color = .data[[color_var]], linetype = .data$replicate_id),
              linewidth = 0.45, alpha = 0.75) +
    geom_point(aes(color = .data[[color_var]]), shape = 16,
               size = 1.9, alpha = 0.95) +
    facet_wrap(
      ~ feature,
      scales = "free_y",
      labeller = as_labeller(facet_label_map)
    ) +
    scale_x_continuous(
      trans = compose_trans("log10", "reverse"),
      breaks = x_breaks,
      minor_breaks = x_minor_breaks,
      labels = x_labels
    ) +
    annotation_logticks(sides = "b", base = 10) +
    scale_linetype_manual(
      name = "Replicate",
      values = c(rep01 = "solid", rep02 = "dashed", single = "dotdash")
    ) +
    labs(
      x = "Log tumour fraction (%)",
      y = "Model probability",
      color = color_label
    ) +
    guides(
      color = "none",
      linetype = "none",
      fill = "none"
    ) +
    theme_classic(base_size = 10) +
    theme(
      strip.text = element_text(face = "bold"),
      panel.border = element_rect(color = "black", fill = NA),
      axis.ticks = element_line(color = "black"),
      axis.text.x = element_text(angle = 45, hjust = 1, vjust = 1, size = 6),
      axis.title.x = element_text(margin = margin(t = 8)),
      plot.margin = margin(5.5, 5.5, 18, 5.5),
      legend.position = if (show_legend) "right" else "none"
    )

  p_feature_lines + p_probability_lines +
    plot_layout(nrow = 1, widths = c(3, 2), guides = "collect") +
    plot_annotation(
      title = plot_title,
      theme = theme(
        plot.title = element_text(hjust = 0.5, face = "bold", size = 14),
        plot.margin = margin(5, 5, 14, 5),
        plot.background = element_rect(fill = "white", colour = NA)
      )
    ) &
    theme(
      panel.border = element_rect(colour = "black", fill = NA),
      panel.background = element_rect(fill = "white", colour = NA),
      plot.background = element_rect(fill = "white", colour = NA),
      strip.text = element_text(face = "bold")
    )
}

