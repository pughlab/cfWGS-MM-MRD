# ── 5. PREDICTION FUNCTION based on pre-trained model ────────────────────
apply_selected <- function(dat, models, thresholds, positive_class = "pos") {
  # ## Score dilution rows with frozen manuscript models
  # Models and thresholds were trained/selected upstream. This function only
  # applies them to rows with complete predictor values and leaves non-scorable
  # rows as NA, which is important for PWGVAL rows missing MRDetect features.
  out <- dat            # start with the full data.frame
  n   <- nrow(dat)
  
  # Check that models and thresholds have at least some overlap
  common <- intersect(names(models), names(thresholds))
  if (length(common) == 0) {
    stop("Model names and threshold names have no overlap!")
  }
  if (!all(names(models) %in% names(thresholds))) {
    warning("Some model names not in thresholds – scoring only the ",
            length(common), " matching combos.")
  }
  
  for (cmb in common) {
    fit <- models[[cmb]]
    thr <- thresholds[[cmb]]
    
    # which predictors the model actually needs
    preds <- setdiff(names(fit$trainingData), ".outcome")
    
    # figure out which rows we can actually score
    can_score <- complete.cases(dat[preds])
    
    # pre‐allocate
    probs <- rep(NA_real_,    n)
    calls <- rep(NA_integer_, n)
    
    # only predict where allowed
    if (any(can_score)) {
      probs[can_score] <- predict(fit,
                                  newdata = dat[can_score, preds, drop = FALSE],
                                  type    = "prob")[[positive_class]]
      calls[can_score] <- as.integer(probs[can_score] >= thr)
    }
    
    # stick them back on
    out[[paste0(cmb, "_prob")]] <- probs
    out[[paste0(cmb, "_call")]] <- calls
  }
  
  out
}

