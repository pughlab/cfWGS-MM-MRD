make_safe_filename_token <- function(x) {
  str_replace_all(x, "[^A-Za-z0-9]+", "_") %>%
    str_replace_all("^_|_$", "")
}

format_lod_percent <- function(x) {
  out <- vapply(
    x,
    function(value) {
      label <- format(value, scientific = FALSE, trim = TRUE, digits = 7)
      if (grepl("\\.", label)) {
        label <- sub("0+$", "", label)
        label <- sub("\\.$", "", label)
      }
      label
    },
    character(1)
  )
  paste0(out, "%")
}

