        .data$panel_type == "Probability" ~ "Negative",
        TRUE ~ NA_character_
      ),
      call = factor(.data$call, levels = c("Negative", "Confirmatory", "Positive"))
    ) %>%
    expand_shared_zero_controls_for_lines()
