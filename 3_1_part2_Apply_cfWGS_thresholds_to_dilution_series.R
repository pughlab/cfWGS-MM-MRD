# ==============================================================================
# 3_1_part2_Apply_cfWGS_thresholds_to_dilution_series.R
#
# Purpose:
#   Apply the trained cfWGS MRD classifiers (logistic regression models and
#   optimal probability thresholds saved by 3_1_Optimize_cfWGS_thresholds.R)
#   to the experimental dilution-series libraries and describe feature and
#   model behavior across the tested dilution range. This experiment does not
#   establish a formally validated analytical limit of detection.
#
#   For each dilution level the script:
#     1. Joins fragmentomics and MRDetect z-score features.
#     2. Generates predicted probabilities using the saved combo models.
#     3. Applies trained thresholds to produce binary MRD calls.
#     4. Plot feature values and model scores against the expected dilution.
#     5. Export source-data CSVs for the dilution-series figures and table.
#
# Analysis unit and denominator:
#   The pooled manuscript analysis contains 48 scored libraries, including
#   technical-replicate libraries as separate observations and four
#   MRD-negative 0% reference libraries. Supplementary Table 7 reports these
#   pooled library-level Spearman correlations. The patient/replicate source
#   tables written here are summarized with equal patient weighting by 3_1C for
#   Figure 3C.
#
# Inputs:
#   - Output_tables_2025/selected_combo_models_2025-09-17.rds and
#     selected_combo_thresholds_2025-09-17.rds for the historical BM/blood
#     dilution analysis.
#   - Output_tables_2025/selected_combo_models_2026-02-16.rds and
#     selected_combo_thresholds_2026-02-16.rds for the current fragmentomics
#     dilution models.
#   - nested_bm_validation_updated4A.rds and
#     nested_blood_validation_updated4_run2.rds for the historical BM/blood
#     plotting thresholds used later in this file.
#   - Results_Fragmentomics/Dilution_series/
#       key_fragmentomics_info_dilution_series.rds
#   - Results_Fragmentomics/
#       fragmentomics_platform_harmonization_reference_parameters.csv
#   - MRDetect_output_winter_2025/Processed_R_outputs/
#       cfWGS_Winter2025Dilution_series_May2025_with_zscore.rds
#   - MRDetect_output_winter_2025/Processed_R_outputs/
#       BM_muts_plots_baseline/cfWGS_MRDetect_BM_data_updated_Feb2026.csv
#   - Fragmentomics_data/Dilution_series/Metadata_dilution_series.csv
#   - Fragmentomics_data/Dilution_series/tumor_fraction_dilution_series.txt
#   - Spring 2026 X Plus 0% dilution metadata and feature files located by the
